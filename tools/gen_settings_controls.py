#!/usr/bin/env python3
# Generates src/NatureFX/Tools/SettingsControls.g.cs from the F8 window (src/NatureFX/NatureFXWindow.cs): every slider,
# switch and chip row that edits a setting directly (S.Name), with its tab, card, label and range, for the debug page's
# settings tab (DevControls). Settings no window control edits plainly are added there at run time (reflection).
# Run it after changing the window: python3 tools/gen_settings_controls.py
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
window = (root / 'src/NatureFX/NatureFXWindow.cs').read_text(encoding='utf-8')
out = root / 'src/NatureFX/Tools/SettingsControls.g.cs'

tabs = re.search(r'string\[\] Tabs = \{(.*?)\};', window, re.S)
tab_names = re.findall(r'"([^"]*)"', tabs.group(1)) if tabs else []
tab_of = {}
for m in re.finditer(r'case (\d+): (Draw\w+)\(\); break;', window):
    i = int(m.group(1))
    tab_of[m.group(2)] = tab_names[i] if i < len(tab_names) else m.group(2)[4:]

arrays = {}
for m in re.finditer(r'static readonly string\[\] (\w+) = \{(.*?)\};', window, re.S):
    arrays[m.group(1)] = '{ ' + ', '.join(re.findall(r'"(?:[^"\\]|\\.)*"', m.group(2))) + ' }'

num = r'(-?[0-9.]+)f?'
slider = re.compile(r'Widgets\.(Slider|IntSlider)\("((?:[^"\\]|\\.)*)",\s*S\.(\w+),\s*' + num + r',\s*' + num + r',\s*v => S\.(\w+) = v[,)]')
switch = re.compile(r'Widgets\.Switch\("((?:[^"\\]|\\.)*)",\s*S\.(\w+),\s*v => S\.(\w+) = v[,)]')
clamp = re.compile(r'int (\w+) = Mathf\.Clamp\(S\.(\w+),')
chips = re.compile(r'Widgets\.Chips\(ref (\w+), (.+?)\)\) \{')
card = re.compile(r'Widgets\.BeginCard\("((?:[^"\\]|\\.)*)"')
method = re.compile(r'private void (Draw\w+)\(')

entries, seen = [], set()
cur_method, cur_card, locals_ = None, '', {}
for line in window.splitlines():
    m = method.search(line)
    if m:
        cur_method, cur_card, locals_ = m.group(1), '', {}
    if cur_method not in tab_of:
        continue
    m = card.search(line)
    if m:
        cur_card = m.group(1)
    m = clamp.search(line)
    if m:
        locals_[m.group(1)] = m.group(2)
    group = tab_of[cur_method] + (' / ' + cur_card if cur_card else '')
    for m in slider.finditer(line):
        kind, label, prop, lo, hi, target = m.groups()
        if prop != target or prop in seen:
            continue
        seen.add(prop)
        entries.append(('Slider', group, label, prop, float(lo), float(hi), kind == 'IntSlider', None))
    for m in switch.finditer(line):
        label, prop, target = m.groups()
        if prop != target or prop in seen:
            continue
        seen.add(prop)
        entries.append(('Switch', group, label, prop, 0, 0, False, None))
    m = chips.search(line)
    if m and m.group(1) in locals_:
        prop = locals_[m.group(1)]
        expr = m.group(2).strip()
        if prop in seen:
            continue
        if expr.startswith('new[]'):
            options = expr[len('new[]'):].strip()
        elif expr in arrays:
            options = arrays[expr]
        else:
            # a public array elsewhere (WeatherController.Names, Rendering.Dlaa.Qualities)
            options = '__expr__' + ('NatureFX.' + expr if expr.startswith('Rendering.') else expr)
        seen.add(prop)
        entries.append(('Chips', group, prop, prop, 0, 0, True, options))

def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def f(x):
    return repr(float(x)) + 'f'

lines = []
for kind, group, label, prop, lo, hi, integer, options in entries:
    if kind == 'Slider':
        step = 1.0 if integer else max((hi - lo) / 200.0, 0.0001)
        get = f'() => S.{prop}'
        set_ = f'v => S.{prop} = Mathf.RoundToInt(v)' if integer else f'v => S.{prop} = v'
        lines.append(f'\t\t\tSetting({cs(group)}, {cs(prop)}, {cs(label)}, {get}, {set_}, {f(lo)}, {f(hi)}, {f(step)});')
    elif kind == 'Switch':
        lines.append(f'\t\t\tSettingSwitch({cs(group)}, {cs(prop)}, {cs(label)}, () => S.{prop}, v => S.{prop} = v);')
    else:
        opts = options[len('__expr__'):] if options.startswith('__expr__') else 'new[] ' + options
        lines.append(f'\t\t\tSettingChips({cs(group)}, {cs(prop)}, {cs(label)}, {opts}, () => S.{prop}, v => S.{prop} = v);')

text = '''// Generated by tools/gen_settings_controls.py from NatureFXWindow.cs: do not edit by hand.
using NatureFX.Nature;
using UnityEngine;

namespace NatureFX.Tools {
	public static partial class DevControls {
		// the F8 window's controls of the settings, for the debug page's settings tab (tab / card, the setting, its label)
		private static void BuildWindowSettings() {
''' + '\n'.join(lines) + '''
		}

		// how many settings the window's controls cover (the rest: added by reflection)
		private const int WindowSettingCount = ''' + str(len(entries)) + ''';
	}
}
'''
out.write_text(text, encoding='utf-8', newline='\n')
print(f'{len(entries)} settings controls -> {out.relative_to(root)}')
